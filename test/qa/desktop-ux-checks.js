async (page) => {
  await page.goto('http://127.0.0.1:3073/');
  await page.waitForFunction(()=>window.desktopFixtureReady === true);
  const checks=[];
  const check=(name,ok,details)=>{checks.push({name,passed:!!ok,details}); if(!ok) throw new Error(name+': '+JSON.stringify(details));};
  await page.locator('#homeGroups').selectOption('local:隔离测试组');
  await page.locator('[data-home-stock="600183"]').click();
  await page.locator('#periodToggle [data-period="week"]').click();
  await page.waitForFunction(()=>State.currentPeriod==='week' && State.currentView==='kline' && State.currentKlineMeta?.period==='week' && State.currentKlineMeta?.code==='600183' && State.currentRawData.length===26);
  await page.locator('#nextStockBtn').click();
  await page.waitForFunction(()=>State.currentStock.code==='600584' && State.currentKlineMeta?.code==='600584' && State.currentKlineMeta?.period==='week' && State.currentRawData.length===26);
  let state=await page.evaluate(()=>({code:State.currentStock.code,period:State.currentPeriod,status:document.getElementById('stockNavigationStatus').textContent}));
  check('next follows the selected group and preserves weekly period',state.code==='600584'&&state.period==='week'&&state.status.includes('2 / 3'),state);
  await page.keyboard.press('Alt+ArrowDown');
  await page.waitForFunction(()=>State.currentStock.code==='002156');
  state=await page.evaluate(()=>({code:State.currentStock.code,period:State.currentPeriod,nextDisabled:document.getElementById('nextStockBtn').disabled}));
  check('Alt+Down reaches final group member without wrap',state.code==='002156'&&state.period==='week'&&state.nextDisabled,state);
  await page.keyboard.press('Alt+ArrowUp');
  await page.waitForFunction(()=>State.currentStock.code==='600584');
  check('Alt+Up moves to previous member',true);
  await page.locator('#homeWatchSearch').fill('长电');
  await page.locator('#homeWatchSearch').press('Alt+ArrowDown');
  check('keyboard shortcut does not hijack an active search input',await page.evaluate(()=>State.currentStock.code==='600584'));
  await page.locator('#homeWatchSearch').fill('');

  const modes=[];
  for(const period of ['day','week','month']) {
    await page.locator('#periodToggle [data-period="'+period+'"]').click();
    await page.waitForFunction(period=>State.currentPeriod===period&&State.currentKlineMeta?.period===period&&State.currentRawData.length>=26,period);
    await page.locator('#nineTurnModeSelect').selectOption('extended');
    const marks=await page.evaluate(()=>State.klineChart.getOption().series[0].markPoint.data.map(m=>m.value));
    check('extended 9+13 renders on '+period,marks.includes('9')&&marks.includes('C13'),marks);
    modes.push({period,marks});
  }
  await page.evaluate(()=>{window.desktopQaChart=State.klineChart;State.klineChart.dispatchAction({type:'dataZoom',start:25,end:85});});
  await page.locator('#nineTurnModeSelect').selectOption('basic');
  let basic=await page.evaluate(()=>({same:State.klineChart===window.desktopQaChart,zoom:State.klineChart.getOption().dataZoom[0],marks:State.klineChart.getOption().series[0].markPoint?.data||[],mode:localStorage.getItem('webstock.nineTurnMode')}));
  check('basic compatibility mode clears extended monthly labels and retains chart/zoom',basic.same&&basic.mode==='basic'&&basic.marks.length===0&&Math.abs(basic.zoom.start-25)<1,basic);
  await page.locator('#nineTurnModeSelect').selectOption('extended');
  const restored=await page.evaluate(()=>({same:State.klineChart===window.desktopQaChart,zoom:State.klineChart.getOption().dataZoom[0],marks:State.klineChart.getOption().series[0].markPoint.data.map(m=>m.value),mode:localStorage.getItem('webstock.nineTurnMode')}));
  check('return to extended retains zoom and persisted mode',restored.same&&restored.mode==='extended'&&restored.marks.includes('C13')&&Math.abs(restored.zoom.start-25)<1,restored);
  if (await page.locator('#nineTurnMethod').getAttribute('open') === '') await page.locator('#nineTurnMethod > summary').click();
  const box=await page.locator('#chartContainer').boundingBox();
  await page.mouse.move(box.x+box.width*.55,box.y+box.height*.35);
  await page.keyboard.down('Control');
  await page.mouse.wheel(0,-140);
  await page.keyboard.up('Control');
  await page.waitForFunction(()=>Math.abs(State.klineChart.getOption().dataZoom[0].start-25)>.1);
  check('Ctrl+wheel changes the visible Kline range',true);
  await page.mouse.move(20,100);
  await page.screenshot({path:'output/playwright/desktop-ux-monthly-extended.png'});
  if (!(await page.locator('#nineTurnMethod').getAttribute('open') === '')) await page.locator('#nineTurnMethod > summary').click();
  if (!(await page.locator('#nineTurnHistory').getAttribute('open') === '')) await page.locator('#nineTurnHistory > summary').click();
  const rules=await page.locator('#nineTurnMethod').innerText();
  check('expanded rules disclose version, history source and event type',rules.includes('sequential-public-rules-v1')&&rules.includes('合成夹具')&&rules.includes('准备9')&&rules.includes('衰竭13'),rules.slice(-1200));
  await page.locator('#nineTurnHistoryEvents').scrollIntoViewIfNeeded();
  await page.screenshot({path:'output/playwright/desktop-ux-rules-history.png'});
  await page.locator('#nineTurnMethod > summary').click();
  await page.locator('#searchInput').fill('gzmt');
  await page.waitForFunction(()=>Array.from(document.querySelectorAll('#stockTbody tr')).some(row=>row.textContent.includes('贵州茅台'))&&document.body.classList.contains('market-drawer-open'));
  const result=page.locator('#stockTbody tr').filter({hasText:'贵州茅台'});
  await result.locator('td').nth(2).click();
  await page.waitForFunction(()=>State.currentStock.code==='600519'&&!document.body.classList.contains('market-drawer-open'));
  state=await page.evaluate(()=>({code:State.currentStock.code,period:State.currentPeriod,status:document.getElementById('stockNavigationStatus').textContent,drawer:document.body.classList.contains('market-drawer-open')}));
  check('global pinyin lookup selects outside current watchlist and retains period',state.code==='600519'&&state.period==='month'&&state.status.includes('1 / 1')&&!state.drawer,state);
  await page.screenshot({path:'output/playwright/desktop-ux-search-result.png'});
  await page.evaluate(checks=>{window.desktopQaResults=checks;},checks);
  return {checks,modes,apiRequests:await page.evaluate(()=>performance.getEntriesByType('resource').filter(entry=>entry.name.includes('/api/')).map(entry=>entry.name))};
}
